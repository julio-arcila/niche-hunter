"""The backtest niche set. Curated before the data it will be measured against.

Gate E needs ~30 niches, not 6: Spearman's SE is about `1/sqrt(N-1)`, so at N=6 the
smallest correlation distinguishable from noise is **0.89** and a null result would
mean nothing. At N=30 it is 0.37. Building these is the real cost of Slice 6.

**Six families of six, not one flat set of thirty.** `lexicon.weights()` scores a
term `1/k` over the family and zeroes any term present in all of it, so family size
is part of the instrument rather than an implementation detail. In a family of two a
shared term IS in every lexicon and weighs 0; in the live family of five, `collapse`
sits in two and weighs 0.5. A flat family of thirty would push most shared terms to
1/6 or lower and the zero row would essentially never fire — the backtest's
relevance rule would be systematically stricter than production's at the same 0.55
threshold, which is a confound directly under the headline. Families of six
reproduce the live construction of five closely.

**These are backtest niches, not production seeds.** They live here, not in
`nh/seeds.py`; the live portfolio stays at 6 and tonight's cron is unaffected. They
are scored with `weights(BACKTEST_LEXICONS[family], BACKTEST_COMMON)`, never
against the live family — see ADR-0026 and `tests/test_lexicon_families.py` for the
measured reason that matters.

**Curated blind, and checkably so.** This file is committed before
`yt_metadata_en.jsonl.gz` finishes downloading. Writing a lexicon, discovering it
selects four channels, and widening it is tuning the definition of the population
against the population — so the sequencing makes that impossible rather than merely
discouraged, and the report cites this commit against the file's mtime.

The inclusion floor is fixed here, before the scan, and niches that fall below it
are **reported as dropped with their counts, never rescued by an edit**. 36 are
curated expecting ~30 to survive.
"""

