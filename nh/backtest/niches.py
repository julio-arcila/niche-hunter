def families() -> dict[str, dict[str, tuple[str, ...]]]:
    """`family -> {slug: lexicon}`. The unit `lexicon.weights()` operates on."""
    out: dict[str, dict[str, tuple[str, ...]]] = {}
    for niche in BACKTEST_NICHES:
        out.setdefault(niche["family"], {})[niche["slug"]] = niche["lexicon"]
    return out


def backtest_weights() -> dict[str, dict[str, float]]:
    """`slug -> {term: weight}`, each family weighed against itself only.

    Never against the live family. Merging them re-weights the live lexicons —
    measured, `crash` falls from 1.00 to 0.032 — with no `LEXICON_VERSION` bump,
    because nobody would have edited a live lexicon (ADR-0026).
    """
